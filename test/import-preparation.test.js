test('CSV options support headerless files, skipped preambles, custom null markers, schema casts, and reports', () => {
  const dataset = parseCSV('Monthly report\nGenerated by Numeriq\nname;count;note\n Ada ;001;-\nBob;2;NA\n', {
    delimiter: ';', skipRows: 2, nullValues: ['-'], schema: { count: 'integer' }
  });
  assert.deepEqual(dataset.rows, [
    { name: 'Ada', count: 1, note: null },
    { name: 'Bob', count: 2, note: null }
  ]);
  assert.equal(dataset.importReport.format, 'csv');
  assert.equal(dataset.importReport.skipRows, 2);
  assert.equal(dataset.importReport.rowsRead, 2);
  assert.deepEqual(dataset.importReport.missingByColumn, { name: 0, count: 0, note: 2 });
  assert.equal(Object.isFrozen(dataset.importReport), true);
  assert.equal(dataset.dropMissing().importReport, null);

  const headerless = parseCSV('Ada;4\nLin;7\n', { header: false, columns: ['name', 'visits'], delimiter: ';' });
  assert.deepEqual(headerless.columns, ['name', 'visits']);
  assert.equal(headerless.rows[1].visits, 7);
  assert.equal(headerless.importReport.hasHeader, false);
});

test('CSV validates row widths by default and emits warnings when lenient mode repairs rows', () => {
  assert.throws(() => parseCSV('a,b\n1,2,extra\n'), /has 3 cells; expected 2/);
  const lenient = parseCSV('a,b\n1,2,extra\n3\n', { strict: false });
  assert.deepEqual(lenient.rows, [{ a: 1, b: 2 }, { a: 3, b: null }]);
  assert.equal(lenient.importReport.warnings.length, 2);
  assert.throws(() => parseCSV('a,b\n1,2', { skipRows: -1 }), ValidationError);
});

test('JSON imports accept record and column-oriented data, schemas, null tokens, and warning reports', () => {
  const records = parseJSON('[{"amount":"10","active":"TRUE"},{"amount":null,"active":"false"}]', {
    schema: { amount: 'number', active: 'boolean' }
  });
  assert.deepEqual(records.rows, [{ amount: 10, active: true }, { amount: null, active: false }]);
  assert.equal(records.importReport.format, 'json');

  assert.throws(() => parseJSON('{"a":[1,2],"b":[3]}'), /equal lengths/);
  const padded = parseJSON('{"a":[1,2],"b":[3]}', { strict: false });
  assert.deepEqual(padded.rows, [{ a: 1, b: 3 }, { a: 2, b: null }]);
  assert.equal(padded.importReport.warnings.length, 1);
});

test('explicit schemas fail clearly, with opt-in invalid-value-to-null reporting', () => {
  assert.throws(() => parseCSV('age\nnot-a-number\n', { schema: { age: 'integer' } }), /CSV row 1, column "age"/);
  assert.throws(() => parseCSV('age\n', { schema: { age: 'unknown-type' } }), /Unsupported data type/);
  const coerced = parseCSV('age\nnot-a-number\n', { schema: { age: 'integer' }, onInvalid: 'null' });
  assert.equal(coerced.rows[0].age, null);
  assert.match(coerced.importReport.warnings[0], /set to null/);
});

test('normalization exposes whitespace controls without coercing identifier columns', () => {
  const trimmed = parseCSV('name,id\n  Ada  ,0012\n');
  assert.deepEqual(trimmed.rows[0], { name: 'Ada', id: '0012' });
  const untrimmed = parseCSV('name\n  Ada  \n', { trimStrings: false });
  assert.equal(untrimmed.rows[0].name, '  Ada  ');
});

test('useSampleDataset provides the same sample through CSV, TSV, and JSON', async () => {
  const defaultSample = await useSampleDataset();
  const tsv = await useSampleDataset('tsv');
  const json = await useSampleDataset({ format: 'json' });
  assert.deepEqual(defaultSample.columns, ['Transaction_ID', 'Date', 'Product', 'Category', 'Quantity', 'Total_Amount']);
  assert.equal(defaultSample.length, 25);
  assert.equal(defaultSample.rows[0].Transaction_ID, 1001);
  assert.equal(defaultSample.rows.at(-1).Transaction_ID, 1025);
  assert.deepEqual(tsv.rows, defaultSample.rows);
  assert.deepEqual(json.rows, defaultSample.rows);
  assert.equal(defaultSample.importReport.source, 'sample:sales.csv');
  await assert.rejects(useSampleDataset('xlsx'), ValidationError);
});

test('loadData detects JSON API responses and supports HTTP methods, headers, and JSON bodies', async (t) => {
  const server = createServer(async (request, response) => {
    let body = '';
    for await (const chunk of request) body += chunk;
    if (request.method !== 'POST' || request.headers['x-numeriq-token'] !== 'verified' || JSON.parse(body).region !== 'north') {
      response.writeHead(400).end('bad request');
      return;
    }
    response.writeHead(200, { 'content-type': 'application/json; charset=utf-8' });
    response.end(JSON.stringify([{ region: 'north', total: 12 }]));
  });
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  t.after(() => new Promise((resolve, reject) => server.close(error => error ? reject(error) : resolve())));
  const { port } = server.address();
  const dataset = await loadData(`http://127.0.0.1:${port}/api/report`, {
    method: 'POST',
    headers: { 'x-numeriq-token': 'verified' },
    body: { region: 'north' }
  });
  assert.deepEqual(dataset.rows, [{ region: 'north', total: 12 }]);
  assert.equal(dataset.importReport.format, 'json');
});

test('explicit projectRoot resolves local files when the process cwd is elsewhere', async t => {
  const projectRoot = await mkdtemp(path.join(os.tmpdir(), 'numeriq-project-'));
  t.after(() => rm(projectRoot, { recursive: true, force: true }));
  await mkdir(path.join(projectRoot, 'dataset'));
  await writeFile(path.join(projectRoot, 'package.json'), '{"name":"sample-app"}');
  await writeFile(path.join(projectRoot, 'dataset', 'custom.csv'), 'id,value\n001,7\n');
  const dataset = await loadCSV('custom.csv', { projectRoot });
  assert.deepEqual(dataset.rows, [{ id: '001', value: 7 }]);
  await assert.rejects(loadCSV('../package.json', { projectRoot }), /must stay inside/);
});

test('loadMany unions columns, reports per-source details, and can deduplicate across files', async () => {
  const combined = await loadMany(['sales.csv', 'sales.csv'], { deduplicateBy: ['Transaction_ID'] });
  assert.equal(combined.length, 25);
  assert.equal(combined.importReport.sourceCount, 2);
  assert.equal(combined.importReport.duplicatesRemoved, 25);
  assert.equal(combined.importReport.rowsImported, 25);
  assert.equal(combined.importReport.sources.length, 2);
  await assert.rejects(loadMany(['sales.csv', 'people.json'], { columnStrategy: 'strict' }), /do not match/);
  const union = await loadMany(['sales.csv', 'people.json']);
  assert.deepEqual(union.columns, ['Transaction_ID', 'Date', 'Product', 'Category', 'Quantity', 'Total_Amount', 'name', 'active']);
  assert.equal(union.length, 27);
});

test('Dataset.profile reports missingness, distinct values, frequent categories, constants, and duplicate rows', () => {
  const dataset = createDataset([
    { status: 'red', value: 1 },
    { status: 'blue', value: null },
    { status: 'red', value: 1 },
    { status: null, value: null }
  ]);
  const report = dataset.profile({ topValues: 2 });
  assert.equal(report.rowCount, 4);
  assert.equal(report.duplicateRows, 1);
  assert.equal(report.duplicateRowPercent, 25);
  assert.deepEqual(report.constantColumns, ['value']);
  assert.deepEqual(report.columns[0].topValues, [{ value: 'red', count: 2 }, { value: 'blue', count: 1 }]);
  assert.equal(report.columns[0].missingPercent, 25);
  assert.equal(report.columns[1].distinct, 1);
  assert.equal(dataset.dropDuplicates().length, 3);
});

test('dropMissing, fillMissing, and castColumn are immutable and have explicit failure behavior', () => {
  const dataset = createDataset([
    { id: 1, score: '2', label: 'ok' },
    { id: 2, score: null, label: 'ok' },
    { id: 3, score: 'bad', label: null },
    { id: 4, score: null, label: null }
  ], { normalization: { inferTypes: false } });
  assert.equal(dataset.dropMissing().length, 1);
  assert.equal(dataset.dropMissing({ columns: ['score', 'label'], how: 'all' }).length, 3);
  assert.throws(() => dataset.dropMissing({ how: 'none' }), ValidationError);

  const filled = dataset.fillMissing('score', (row, index) => index + 10);
  assert.equal(filled.rows[1].score, 11);
  assert.equal(dataset.rows[1].score, null);

  const coerced = dataset.castColumn('score', 'integer', { errors: 'coerce' });
  assert.deepEqual(coerced.rows.map(row => row.score), [2, null, null, null]);
  assert.equal(typeof createDataset([{ value: 2 }]).castColumn('value', 'string').rows[0].value, 'string');
  assert.equal(createDataset([{ day: '2024-02-29' }]).castColumn('day', 'date').rows[0].day.toISOString(), '2024-02-29T00:00:00.000Z');
  assert.throws(() => dataset.castColumn('score', 'integer'), /row 2/);
  assert.throws(() => createDataset([{ day: '2024-02-30' }]).castColumn('day', 'date'), /Cannot cast/);
  assert.throws(() => dataset.castColumn('score', 'unsupported', { errors: 'coerce' }), /Unsupported data type/);
});
